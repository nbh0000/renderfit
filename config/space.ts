/** 면적(㎡)에 해당하는 가구 규모 가이드 */
export function furnitureScaleGuide(areaM2: number): string {
  const tier = FURNITURE_SCALE_TIERS.find((item) => areaM2 <= item.maxM2);
  return (tier ?? FURNITURE_SCALE_TIERS[FURNITURE_SCALE_TIERS.length - 1]).guide;
}
